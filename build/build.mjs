/*
 * Strands store build — precompiles the store's JSX and removes Babel Standalone.
 *
 * WHY: the store page currently ships Babel Standalone (~900 KB gzipped) and
 * transpiles every .jsx in the browser on each load. This script transpiles the
 * JSX ahead of time (with esbuild) into one plain-JS file, so the live page loads
 * production React + a precompiled bundle and NO Babel. Same output, just moved
 * from the visitor's device to build time.
 *
 * RUN:  cd build && npm install && npm run build
 * Requires Node 18+. Run it whenever you edit any store .jsx, then commit the
 * regenerated ui_kits/store/index.html and ui_kits/store/_bundle.store.js.
 *
 * This only touches ui_kits/store/. The account/dashboard pages are untouched.
 */
import { transformSync } from "esbuild";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const storeDir = path.join(root, "ui_kits", "store");
const htmlPath = path.join(storeDir, "index.html");
const pagePath = path.join(storeDir, "page.jsx");
const bundlePath = path.join(storeDir, "_bundle.store.js");

// Components are plain global scripts (they read window.* and expose via
// Object.assign(window, ...)), loaded in this order today. page.jsx is the
// Page component + mount() lifted out of the inline <script> on first run.
const order = [
  "responsive.jsx", "Header.jsx", "Hero.jsx", "Statement.jsx", "PhotoStrip.jsx",
  "OverTime.jsx", "Science.jsx", "Standards.jsx", "Reviews.jsx", "Footer.jsx",
  "Checkout.jsx", "page.jsx",
];

let html = readFileSync(htmlPath, "utf8");

// --- One-time: lift the inline Babel page script into page.jsx -------------
const inlineRe = /<script type="text\/babel" data-presets="react">([\s\S]*?)<\/script>/;
const inlineMatch = html.match(inlineRe);
if (inlineMatch) {
  if (!existsSync(pagePath)) {
    writeFileSync(pagePath, inlineMatch[1].trim() + "\n");
    console.log("• extracted inline page script -> ui_kits/store/page.jsx");
  }
  html = html.replace(inlineRe, "");
}
if (!existsSync(pagePath)) {
  throw new Error("page.jsx not found and no inline page script to extract — aborting.");
}

// --- Transpile each source file (JSX -> React.createElement) & concatenate --
// Each file is wrapped in its own IIFE so top-level `const {Button} = ...`
// declarations from different files don't collide in one shared scope.
const xform = (code, name) =>
  transformSync(code, {
    loader: "jsx",
    jsx: "transform",
    jsxFactory: "React.createElement",
    jsxFragment: "React.Fragment",
    minify: true,
    sourcefile: name,
  }).code;

let bundle = "/* AUTO-GENERATED by `npm run build` — do not edit by hand. */\n";
for (const file of order) {
  const src = readFileSync(path.join(storeDir, file), "utf8");
  bundle += `\n/* ${file} */\n(()=>{\n${xform(src, file)}\n})();\n`;
}
writeFileSync(bundlePath, bundle);
console.log(`• wrote ui_kits/store/_bundle.store.js (${bundle.length} bytes)`);

// --- Rewrite index.html to production form (idempotent) --------------------
html = html
  // production React (no-op if already swapped)
  .replace(/react\.development\.js/g, "react.production.min.js")
  .replace(/react-dom\.development\.js/g, "react-dom.production.min.js")
  // drop Babel Standalone
  .replace(/\s*<script src="https:\/\/unpkg\.com\/@babel\/standalone[^"]*"[^>]*><\/script>/g, "")
  // drop the per-file text/babel component scripts
  .replace(/\s*<script type="text\/babel" src="[^"]+"><\/script>/g, "");

// ensure the precompiled bundle is loaded exactly once, just before </body>
if (!html.includes("_bundle.store.js")) {
  html = html.replace(/<\/body>/, '<script src="_bundle.store.js"></script>\n</body>');
}
writeFileSync(htmlPath, html);
console.log("• rewrote ui_kits/store/index.html (production: no Babel, precompiled bundle)");
console.log("Done. Commit index.html, _bundle.store.js and page.jsx, then deploy.");
